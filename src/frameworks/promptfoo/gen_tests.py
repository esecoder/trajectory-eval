#!/usr/bin/env python3
"""
gen_tests.py — generate Promptfoo test cases from the trajectory set.

⚠️ GENERATED, NOT HAND-WRITTEN, AND THAT IS THE POINT. A test file maintained by hand
drifts from the data it is supposed to cover: items get added to the trajectory set and
never to the gate, so the gate keeps passing while coverage quietly falls. That is the
same class of defect as a stale README, and the fix is the same one this repository uses
everywhere — make it mechanical.

Run:
    python src/frameworks/promptfoo/gen_tests.py
writes `tests.generated.yaml`, which `promptfooconfig.yaml` references.
"""

from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.dirname(os.path.dirname(HERE))
if SRC not in sys.path:
    sys.path.insert(0, SRC)

from schema import DATA_DIR, load_jsonl, load_trajectories  # noqa: E402

OUT = os.path.join(HERE, "tests.generated.yaml")


def yaml_escape(s: str) -> str:
    """Emit a double-quoted YAML scalar safely.

    Trajectories contain newlines, quotes and backslashes. A hand-rolled emitter that
    handles only the happy path produces a file that loads for 19 items and silently
    truncates the 20th, so everything is escaped explicitly.
    """
    out = s.replace("\\", "\\\\").replace('"', '\\"')
    out = out.replace("\n", "\\n").replace("\r", "")
    return f'"{out}"'


def main() -> int:
    trajectories = load_trajectories()
    gold_rows = load_jsonl(os.path.join(DATA_DIR, "gold.jsonl"))
    gold = {r["trajectory_id"]: r for r in gold_rows}

    lines = [
        "# GENERATED by gen_tests.py — do not edit by hand.",
        "# One test case per trajectory. Regenerate after changing the trajectory set,",
        "# because a hand-maintained gate silently stops covering new items.",
        "",
    ]
    for t in trajectories:
        g = gold[t.id]
        composite = f"{g.get('composite', 0):.2f}"
        lines += [
            f"- description: {yaml_escape(t.id + ' — ' + t.title)}",
            "  vars:",
            f"    id: {yaml_escape(t.id)}",
            f"    transcript: {yaml_escape(t.transcript())}",
            f"    expect_verdict: {yaml_escape(g['verdict'])}",
            f"    expect_veto: {yaml_escape('true' if g['verdict'].startswith('FAIL_') else 'false')}",
            f"    gold_composite: {yaml_escape(composite)}",
            "",
        ]

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    vetoes = [r["trajectory_id"] for r in gold_rows if r["verdict"].startswith("FAIL_")]
    print(f"gen_tests.py — wrote {OUT}")
    print(f"  test cases     : {len(trajectories)}")
    print(f"  expect_veto    : {vetoes}")
    print("  ⚠️ if this count does not match the trajectory set, the gate is not covering")
    print("     everything — regenerate rather than editing tests.generated.yaml.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
